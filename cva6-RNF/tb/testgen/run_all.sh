# run_all.sh — run every generated vector through a fresh vsim invocation.
#
# The HN-F state is reset to its post-reset baseline on every new vsim
# elaboration, so re-running Questa per vector is the cleanest way to
# guarantee no state bleeds between tests. The vlog/sccom build is
# reused — only the vsim phase is repeated.
#
# Usage (run from cva6-RNF/tb/):
#   QUESTA=/path/to/questa ./testgen/run_all.sh                  # all vectors
#   QUESTA=...             ./testgen/run_all.sh --bfs-only       # skip fuzz/
#   QUESTA=...             ./testgen/run_all.sh --fuzz-only      # only fuzz/
#   QUESTA=...             ./testgen/run_all.sh --pattern '*_A_*' # glob filter
#
# Environment:
#   QUESTA          — path to Questa root (required if QUESTA expected by Makefile)
#   PER_VEC_TIMEOUT — seconds before SIGKILL on a hung vsim   (default 120)
#   ADDR            — replay line address in hex              (default 0x80000200)
#   KEEP_LOGS       — 0/1: keep per-vector .log files          (default 1)
#
# Output:
#   testgen/run_all_logs/<vector>.log     per-vector sim log
#   testgen/run_all_summary.tsv           one row per vector
#   stdout: live PASS/FAIL/TIMEOUT line per vector + final tally

set -u
set -o pipefail

# ── paths ────────────────────────────────────────────────────────────────────
HERE="$(cd "$(dirname "$0")" && pwd)"        # cva6-RNF/tb/testgen
TB="$(cd "$HERE/.." && pwd)"                 # cva6-RNF/tb
BUILD="$TB/questa_build"
LOG_DIR="$HERE/run_all_logs"
SUMMARY="$HERE/run_all_summary.tsv"

# ── knobs ────────────────────────────────────────────────────────────────────
PER_VEC_TIMEOUT="${PER_VEC_TIMEOUT:-120}"
ADDR="${ADDR:-0x80000200}"
KEEP_LOGS="${KEEP_LOGS:-1}"

# COVERAGE=1 forwards -coverage to vsim and saves a per-vector UCDB
# alongside the .log. The Makefile's COVERAGE knob exports the same
# variable; we just check whether the build supports it.
COVERAGE="${COVERAGE:-0}"

# ── Address sweep ────────────────────────────────────────────────────────────
# Exhaustive mode: run each vector at multiple addresses to exercise
# different L3 / snoop-filter set indices and a same-set / different-tag
# pair (L3 collision). Override ADDRS to use a custom list.
#
# HNF param-derived index regions (hnf_param.v):
#   L3:  bits [17:6]   (4096 sets × 16 ways)
#   SF:  bits [18:6]   (8192 sets × 16 ways)
#
#   0x80000200 - baseline (L3 set 0x008, SF set 0x008, tag bits = 0x2000)
#   0x80000a00 - different L3 set (bit 9 changed)
#   0x80040200 - SAME L3 set as baseline, different tag → L3 collision
#   0x80100200 - different L3 set + different SF set (bit 20)
#   0x80800200 - different L3+SF set + high-tag region
ADDRS="${ADDRS:-0x80000200 0x80000a00 0x80040200 0x80100200 0x80800200}"
SWEEP_ADDRS="${SWEEP_ADDRS:-0}"   # 0=use $ADDR only; 1=iterate over $ADDRS

PATTERN="*.txt"
INCLUDE_BFS=1
INCLUDE_FUZZ=1
INCLUDE_BURST=1
INCLUDE_CROSS=1
INCLUDE_MURPHI=1  # vectors_murphi/ generated by gen_from_murphi.py
LIMIT=0           # 0 = no limit; >0 truncates the vector list
SAMPLE=0          # 0 = no sampling; >0 picks SAMPLE random vectors
LIST_ONLY=0       # 1 = print the matching vectors and exit
while [[ $# -gt 0 ]]; do
    case "$1" in
        --bfs-only)    INCLUDE_FUZZ=0; INCLUDE_BURST=0; INCLUDE_CROSS=0; INCLUDE_MURPHI=0 ;;
        --fuzz-only)   INCLUDE_BFS=0;  INCLUDE_BURST=0; INCLUDE_CROSS=0; INCLUDE_MURPHI=0 ;;
        --burst-only)  INCLUDE_BFS=0;  INCLUDE_FUZZ=0;  INCLUDE_CROSS=0; INCLUDE_MURPHI=0 ;;
        --cross-only)  INCLUDE_BFS=0;  INCLUDE_FUZZ=0;  INCLUDE_BURST=0; INCLUDE_MURPHI=0 ;;
        --murphi-only) INCLUDE_BFS=0;  INCLUDE_FUZZ=0;  INCLUDE_BURST=0; INCLUDE_CROSS=0 ;;
        --pattern)    PATTERN="$2"; shift ;;
        --sweep)      SWEEP_ADDRS=1  ;;       # iterate over $ADDRS
        --addrs)      ADDRS="$2"; SWEEP_ADDRS=1; shift ;;
        --limit)      LIMIT="$2";  shift ;;   # cap to first N (post-sort)
        --sample)     SAMPLE="$2"; shift ;;   # random N (seeded by $RANDOM)
        --list)       LIST_ONLY=1 ;;          # show selected vectors, don't run
        -h|--help)
            sed -n '2,/^$/p' "$0" | sed 's/^# \{0,1\}//'
            exit 0
            ;;
        *)
            echo "unknown arg: $1" >&2; exit 2 ;;
    esac
    shift
done

# Build the list of (vector, addr) test instances. Without --sweep, each
# vector runs once at $ADDR. With --sweep, each vector runs once per
# address in $ADDRS.
if [[ "$SWEEP_ADDRS" == "1" ]]; then
    read -r -a TEST_ADDRS <<<"$ADDRS"
else
    TEST_ADDRS=("$ADDR")
fi

# ── checks ───────────────────────────────────────────────────────────────────
if [[ ! -d "$BUILD" ]]; then
    echo "ERROR: $BUILD does not exist. Build first:" >&2
    echo "       cd $TB && make QUESTA=\$QUESTA all REPLAY=1 MSHR_OBS=1" >&2
    exit 1
fi
if ! command -v vsim >/dev/null 2>&1; then
    if [[ -n "${QUESTA:-}" ]]; then
        export PATH="$QUESTA/bin:$PATH"
    fi
    if ! command -v vsim >/dev/null 2>&1; then
        echo "ERROR: vsim not in PATH. Set QUESTA=..." >&2
        exit 1
    fi
fi

# License preflight — bail out before launching 100s of vsim runs that
# would all fail with "Unable to checkout a license" otherwise. Probe with
# vsim -version which exits fast and exercises the license env.
if [[ -z "${LM_LICENSE_FILE:-}${MGLS_LICENSE_FILE:-}${SALT_LICENSE_SERVER:-}" ]]; then
    echo "ERROR: no Questa license environment variable is set." >&2
    echo "       Export one of LM_LICENSE_FILE, MGLS_LICENSE_FILE, or" >&2
    echo "       SALT_LICENSE_SERVER before running this script." >&2
    exit 1
fi
if ! vsim -version >/dev/null 2>&1; then
    echo "ERROR: 'vsim -version' failed. Check license server reachability." >&2
    echo "       LM_LICENSE_FILE=${LM_LICENSE_FILE:-<unset>}" >&2
    exit 1
fi

# ── collect vector list ──────────────────────────────────────────────────────
mapfile -t VECTORS < <(
    {
        [[ $INCLUDE_BFS    -eq 1 ]] && find "$HERE/vectors"         -maxdepth 1 -name "$PATTERN"
        [[ $INCLUDE_FUZZ   -eq 1 ]] && find "$HERE/vectors/fuzz"    -maxdepth 1 -name "$PATTERN" 2>/dev/null
        [[ $INCLUDE_BURST  -eq 1 ]] && find "$HERE/vectors/burst"   -maxdepth 1 -name "$PATTERN" 2>/dev/null
        [[ $INCLUDE_CROSS  -eq 1 ]] && find "$HERE/vectors/cross"   -maxdepth 1 -name "$PATTERN" 2>/dev/null
        [[ $INCLUDE_MURPHI -eq 1 ]] && find "$HERE/vectors_murphi"  -maxdepth 1 -name "$PATTERN" 2>/dev/null
    } | sort
)

# --sample N: shuffle then trim to N (uses 'shuf' if available, else awk)
if [[ "$SAMPLE" -gt 0 ]]; then
    if command -v shuf >/dev/null 2>&1; then
        mapfile -t VECTORS < <(printf '%s\n' "${VECTORS[@]}" | shuf | head -n "$SAMPLE")
    else
        mapfile -t VECTORS < <(printf '%s\n' "${VECTORS[@]}" \
            | awk 'BEGIN{srand()} {print rand()" "$0}' | sort | cut -d' ' -f2- \
            | head -n "$SAMPLE")
    fi
fi
# --limit N: trim to first N (post-sort, post-sample)
if [[ "$LIMIT" -gt 0 ]]; then
    VECTORS=("${VECTORS[@]:0:$LIMIT}")
fi
# --list: show selection and exit
if [[ "$LIST_ONLY" -eq 1 ]]; then
    printf '%s\n' "${VECTORS[@]}"
    exit 0
fi
if [[ ${#VECTORS[@]} -eq 0 ]]; then
    echo "no vectors matched (pattern='$PATTERN', bfs=$INCLUDE_BFS, fuzz=$INCLUDE_FUZZ)" >&2
    exit 1
fi

mkdir -p "$LOG_DIR"
printf 'vector\taddr\tstatus\twall_s\tdetail\n' > "$SUMMARY"

n_total=$(( ${#VECTORS[@]} * ${#TEST_ADDRS[@]} ))
n_pass=0; n_fail=0; n_timeout=0; n_error=0
i=0

addr_list_str="${TEST_ADDRS[*]}"
echo "[run_all] ${#VECTORS[@]} vectors × ${#TEST_ADDRS[@]} addr(s) = $n_total tests  build=$BUILD  timeout=${PER_VEC_TIMEOUT}s"
echo "          addrs:    $addr_list_str"
echo "          coverage: $([[ $COVERAGE == 1 ]] && echo on || echo off)"
echo

# ── per-(vector, address) loop ──────────────────────────────────────────────
for vec in "${VECTORS[@]}"; do
    base="$(basename "$vec" .txt)"
    for cur_addr in "${TEST_ADDRS[@]}"; do
        i=$((i + 1))
        if [[ ${#TEST_ADDRS[@]} -gt 1 ]]; then
            # tag log file with addr suffix to avoid collisions
            name="${base}__${cur_addr}"
        else
            name="$base"
        fi
        log="$LOG_DIR/$name.log"

        cov_arg=""
        cov_do=""
        cov_onfinish=""
        ucdb_path="$LOG_DIR/$name.ucdb"
        if [[ "$COVERAGE" == "1" ]]; then
            cov_arg="-coverage"
            cov_do="coverage save $ucdb_path;"
            # The TB watchdog calls \$finish at 2ms (tlm_rnf_hnf_tb.sv:106),
            # which by default exits vsim before the -do script reaches
            # 'coverage save'. Make \$finish behave like \$stop so the
            # -do continues. quit -f then ends the sim after the save.
            cov_onfinish="-onfinish stop"
        fi

        t0=$(date +%s)
        set +e
        timeout --kill-after=5s "${PER_VEC_TIMEOUT}s" \
            bash -c "cd '$BUILD' && \
                     REPLAY_VECTOR='$vec' REPLAY_ADDR='$cur_addr' \
                     vsim -c -t 10ps -suppress 3009 $cov_arg $cov_onfinish work.tlm_rnf_hnf_tb \
                          -do 'log -r /*; run -all; $cov_do quit -f;' \
                          > '$log' 2>&1"
        rc=$?
        set -e
        t1=$(date +%s)
        dt=$((t1 - t0))

        # ── classify result ────────────────────────────────────────────────
        # Priority: TIMEOUT > DEADLOCK > sim ERROR > DATA_FAIL > oracle FAIL > PASS
        status="ERROR"; detail=""
        if [[ $rc -eq 124 || $rc -eq 137 ]]; then
            status="TIMEOUT"; detail="vsim killed after ${PER_VEC_TIMEOUT}s"
            n_timeout=$((n_timeout + 1))
        elif grep -q "DEADLOCK" "$log"; then
            status="DEADLOCK"; detail="$(grep -m1 DEADLOCK "$log" | tr -s ' ')"
            n_fail=$((n_fail + 1))
        elif grep -qE "Errors: [^0]" "$log"; then
            status="ERROR"; detail="$(grep -m1 'Errors:' "$log")"
            n_error=$((n_error + 1))
        elif grep -q "DATA_CHECK_RESULT: FAIL" "$log"; then
            status="DATA_FAIL"; detail="$(grep -m1 'DATA_CHECK_RESULT: FAIL' "$log" | tr -s ' ')"
            n_fail=$((n_fail + 1))
        else
            oracle_out="$(python3 "$HERE/oracle.py" "$vec" "$log" 2>&1 || true)"
            if echo "$oracle_out" | grep -q '^# Final result:     PASS'; then
                status="PASS"; detail=""
                n_pass=$((n_pass + 1))
            else
                mismatch="$(echo "$oracle_out" | grep -m1 'FAIL' || true)"
                status="FAIL"; detail="${mismatch:-oracle FAIL}"
                n_fail=$((n_fail + 1))
            fi
        fi

        printf '%-60s  %s  %-8s  %3ds  %s\n' "$base" "$cur_addr" "$status" "$dt" "$detail"
        printf '%s\t%s\t%s\t%d\t%s\n' "$base" "$cur_addr" "$status" "$dt" "$detail" >> "$SUMMARY"

        if [[ "$KEEP_LOGS" != "1" && "$status" == "PASS" ]]; then
            rm -f "$log"
            # Keep UCDB even on PASS — coverage merge needs it.
        fi
    done
done

# ── summary ──────────────────────────────────────────────────────────────────
echo
echo "[run_all] done"
printf '  total    %d\n'  "$n_total"
printf '  PASS     %d\n'  "$n_pass"
printf '  FAIL     %d\n'  "$n_fail"
printf '  TIMEOUT  %d\n'  "$n_timeout"
printf '  ERROR    %d\n'  "$n_error"
echo
echo "summary: $SUMMARY"
echo "logs:    $LOG_DIR/"

# Exit non-zero if anything besides PASS
[[ $((n_fail + n_timeout + n_error)) -eq 0 ]]
