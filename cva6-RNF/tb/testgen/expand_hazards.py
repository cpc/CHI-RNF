"""
expand_hazards.py — generate composite "pending request" states for the
HN-F FSM.

The base FSM (hnf_fsm.yaml) models per-line coherence with one
transaction in flight. When a second REQ arrives during a transient
(CAM hazard), the real HNF either RetryAcks (AllowRetry=1) or
allocates a stalled MSHR slot (AllowRetry=0). Either way, the second
REQ is eventually serviced. This script adds the state machinery to
model that — composite states `<state>__PEND_<peer>_<op>` carry both
the in-flight transaction's progress AND the queued peer REQ.

What gets generated, per transient `T_<phase>_<rnf>` and per peer op `O`:

  1. Hazard entry edge:
       T_<phase>_<rnf>  +  REQ_<peer>_<O>__HAZARD  →  T_<phase>_<rnf>__PEND_<peer>_<O>

  2. Mirrored completion edges (for every original outgoing edge of the
     transient that lands in a downstream state, add a matching edge from
     the PEND variant landing in the downstream's PEND variant):
       T_<phase>_<rnf>__PEND_<peer>_<O>  +  <completion_event>  →  <next>__PEND_<peer>_<O>

  3. Resolution edges from stable states with pending REQs — when the
     in-flight transaction has retired and we land in a stable
     `<stable>__PEND_<peer>_<O>` state, an auto-event starts the
     queued peer's transaction:
       <stable>__PEND_<peer>_<O>  +  AUTO_START_<peer>_<O>  →  <appropriate T_phase_<peer>>

The "appropriate T_phase_<peer>" is the SAME state the FSM would land
in if `REQ_<peer>_<O>` arrived in `<stable>` directly — looked up by
re-querying the base FSM.

Output: emit YAML edges to stdout, intended to be appended to
hnf_fsm.yaml manually after review (so the user keeps control over what
ends up in the source-of-truth FSM file).

Usage:
  ./expand_hazards.py > hazards_expansion.yaml
  cat hazards_expansion.yaml >> hnf_fsm.yaml
"""

import os
import sys

try:
    import yaml
except ImportError:
    sys.exit("PyYAML required: pip install --user --break-system-packages pyyaml")

HERE = os.path.dirname(os.path.abspath(__file__))
FSM_PATH = os.path.join(HERE, "hnf_fsm.yaml")


# Peer ops the hazard machinery covers (must match what hnf_fsm.yaml
# already has hazard self-loops for, sans __HAZARD suffix).
PEER_OPS = [
    "ReadClean", "ReadUnique", "MakeUnique",
    "CleanShared", "CleanUnique", "CleanInvalid",
    "ReadNoSnp", "WriteNoSnpFull", "WriteBackFull", "WriteCleanFull",
]

# Transients we model pending states for. (state_name, in_flight_rnf, peer_rnf)
TRANSIENT_INFO = [
    ("T_FILL_A", "A", "B"),
    ("T_FILL_B", "B", "A"),
    ("T_SNP_A",  "A", "B"),
    ("T_SNP_B",  "B", "A"),
    ("T_ACK_A",  "A", "B"),
    ("T_ACK_B",  "B", "A"),
]


def load_base_fsm(path=FSM_PATH):
    with open(path) as f:
        d = yaml.safe_load(f)
    states = d["states"]
    edges  = d["edges"]
    # Build adjacency: from_state -> [(event, to_state, action), ...]
    adj = {s: [] for s in states}
    for e in edges:
        adj[e["from"]].append((e["event"], e["to"], e.get("action", "")))
    return states, edges, adj


def look_up_destination(adj, start_state, peer, op):
    """If REQ_<peer>_<op> arrives in start_state, where does the FSM go?
    Returns the destination state name, or None if no such edge exists."""
    event = f"REQ_{peer}_{op}"
    for ev, to, _act in adj[start_state]:
        if ev == event:
            return to
    return None


def main():
    states, edges, adj = load_base_fsm()

    new_states  = {}   # name -> {transient: bool}
    new_edges   = []   # list of dicts matching the YAML edge format

    print("# ════════════════════════════════════════════════════════════════════════")
    print("# Auto-generated by expand_hazards.py — DO NOT EDIT BY HAND")
    print("# Composite pending-state expansion for CAM-hazard handling. Each new")
    print("# state encodes (in-flight transient, queued peer REQ) so the FSM keeps")
    print("# memory of REQ2 and eventually services it after REQ1 retires.")
    print("# ════════════════════════════════════════════════════════════════════════")
    print()

    # ── For each transient × peer op, build the pending chain ────────────
    for t_name, in_flight, peer in TRANSIENT_INFO:
        for op in PEER_OPS:
            pend_suffix = f"__PEND_{peer}_{op}"

            # 1. Replace the existing self-loop hazard edge with one that
            #    goes to the composite pending-transient state.
            pend_transient = t_name + pend_suffix
            new_states[pend_transient] = {"transient": True}
            new_edges.append({
                "from":   t_name,
                "event":  f"REQ_{peer}_{op}__HAZARD",
                "to":     pend_transient,
                "action": f"queue {peer}_{op}; transient continues",
            })

            # 2. Mirror the original transient's completion edges so the
            #    queued REQ is carried along until the in-flight one retires.
            #    For each edge T_X_<inflight> --event--> <to>, add
            #    pend_transient --event--> <to>__PEND_<peer>_<op>.
            for ev, to, act in adj.get(t_name, []):
                # Skip if this is itself a hazard edge — we're replacing those.
                if ev.endswith("__HAZARD"):
                    continue
                pend_to = to + pend_suffix
                new_states.setdefault(pend_to, {
                    "transient": states[to].get("transient", False)
                })
                new_edges.append({
                    "from":   pend_transient,
                    "event":  ev,
                    "to":     pend_to,
                    "action": f"{act} (with {peer}_{op} queued)",
                })

    # ── For each stable_state__PEND, add the AUTO_START resolution edge ──
    # When the in-flight transaction has retired we're in a stable state
    # like SC_A__PEND_B_ReadClean. The peer's queued REQ now starts —
    # look up where REQ_<peer>_<op> would go from the stable state in the
    # BASE FSM, and emit an auto-event to that destination.
    stable_pend_states = {
        s: info for s, info in new_states.items()
        if not info.get("transient", False) and "__PEND_" in s
    }
    for pend_state in stable_pend_states:
        # Parse: <stable>__PEND_<peer>_<op>
        before, _, suffix = pend_state.partition("__PEND_")
        peer = suffix[0]
        op   = suffix[2:]  # skip "<peer>_"
        # Look up the destination in the BASE FSM from the stable state
        dest = look_up_destination(adj, before, peer, op)
        if dest is None:
            # The base FSM doesn't model this REQ from this stable state
            # (e.g., REQ_B_WriteBackFull from SC_A — write-back from a
            # non-owner is not in the modelled set). Skip — no resolution
            # edge, the PEND state is effectively a "drop" terminal.
            continue
        new_edges.append({
            "from":   pend_state,
            "event":  f"AUTO_START_{peer}_{op}",
            "to":     dest,
            "action": f"in-flight retired; start queued {peer}_{op}",
        })

    # ── Merge into hnf_fsm.yaml in place ─────────────────────────────────
    with open(FSM_PATH) as f:
        lines = f.readlines()

    # Find the last line of the `states:` block (last line starting with 2-space
    # indent before the `edges:` block) and insert new state lines there.
    edges_idx = next(i for i, ln in enumerate(lines) if ln.startswith("edges:"))
    # Insert states just before `edges:` (and before any blank lines / comments)
    state_insert_idx = edges_idx
    while state_insert_idx > 0 and lines[state_insert_idx - 1].strip() == "":
        state_insert_idx -= 1

    state_lines = ["\n", "  # ── auto-generated pending-state expansion (expand_hazards.py) ──\n"]
    for name, info in sorted(new_states.items()):
        flag = "true" if info.get("transient", False) else "false"
        state_lines.append(f"  {name+':':70s} {{ transient: {flag} }}\n")
    state_lines.append("\n")

    # Insert new edges at end of file
    edge_lines = ["\n", "  # ════════════════════════════════════════════════════════════════════════\n",
                  "  # Auto-generated pending-state edges (expand_hazards.py)\n",
                  f"  # {len(new_states)} new states + {len(new_edges)} new edges encoding the\n",
                  "  # CAM-hazard pending-REQ machinery. Each composite state\n",
                  "  # `<state>__PEND_<peer>_<op>` carries (in-flight transient, queued peer\n",
                  "  # REQ). Re-run `expand_hazards.py` after editing the base FSM above\n",
                  "  # to regenerate these.\n",
                  "  # ════════════════════════════════════════════════════════════════════════\n"]
    for e in new_edges:
        edge_lines.append(
            f"  - {{ from: {e['from']+',':50s} "
            f"event: {e['event']+',':62s} "
            f"to: {e['to']+',':50s} "
            f"action: \"{e['action']}\" }}\n"
        )

    # Rebuild file
    out_lines = lines[:state_insert_idx] + state_lines + lines[state_insert_idx:] + edge_lines
    with open(FSM_PATH, "w") as f:
        f.writelines(out_lines)

    print(f"merged {len(new_states)} states + {len(new_edges)} edges into {FSM_PATH}",
          file=sys.stderr)


if __name__ == "__main__":
    main()
